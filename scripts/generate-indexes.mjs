// Generates src/components/index.ts and src/global.d.ts from every src/components/<Folder>/index.ts.
// Run automatically by `npm run build`.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src')
const componentsDir = join(root, 'components')
const folders = readdirSync(componentsDir, { withFileTypes: true }).filter(d => d.isDirectory() && existsSync(join(componentsDir, d.name, 'index.ts'))).map(d => d.name).sort()

const names = []
const lines = ['// AUTO-GENERATED by scripts/generate-indexes.mjs — do not edit.']
for (const folder of folders) {
  const source = readFileSync(join(componentsDir, folder, 'index.ts'), 'utf8')
  const found = [...source.matchAll(/export (?:const (\w+) = createElementComponent|\{ default as (\w+) \})/g)].map(m => m[1] ?? m[2])
  names.push(...found)
  lines.push(`export * from './${folder}'`)
}
writeFileSync(join(componentsDir, 'index.ts'), lines.join('\n') + '\n')

const globalDts = [
  '// AUTO-GENERATED by scripts/generate-indexes.mjs — do not edit.',
  '// Enables IDE/Volar completion for globally registered components (`app.use(Vue3BootstrapComponents)`).',
  "// Add `\"types\": [\"vue3-bootstrap-components/global\"]` to tsconfig.json `compilerOptions`.",
  "import type * as Components from './components'",
  '',
  "declare module 'vue' {",
  '  export interface GlobalComponents {',
  ...names.map(n => `    ${n}: typeof Components.${n}`),
  '  }',
  '}',
  '',
  'export {}',
  ''
].join('\n')
writeFileSync(join(root, 'global.d.ts'), globalDts)
writeFileSync(join(root, 'component-names.ts'), `// AUTO-GENERATED by scripts/generate-indexes.mjs — do not edit.\nexport const componentNames = ${JSON.stringify(names, null, 2)} as const\n`)
console.log(`Generated exports for ${names.length} components in ${folders.length} folders.`)
